const fs = require("fs");
const path = require("path");
const {
  withAppBuildGradle,
  withDangerousMod,
} = require("expo/config-plugins");

/**
 * Release signing, with a fail-closed default.
 *
 * The Expo template signs `release` with the debug keystore. That is fine for
 * a local test install and wrong for every production artifact: Play rejects
 * it, and two builds from different machines are not the same app identity.
 *
 * This plugin writes `android/app/release-signing.gradle` and applies it at the
 * end of `android/app/build.gradle`. The generated script:
 *
 *   - keeps the debug build type on the debug keystore;
 *   - signs the release build type from a real keystore, read from
 *     `UXCOMMUNITY_ANDROID_STORE_FILE` / `..._STORE_PASSWORD` /
 *     `..._KEY_ALIAS` / `..._KEY_PASSWORD` or from `android/keystore.properties`;
 *   - throws before any release task runs when those credentials are missing,
 *     so a release build can never silently fall back to the debug key.
 *
 * EAS Build manages its own upload credentials and injects them after Prebuild,
 * so the fail-closed script is skipped when EAS_BUILD is set. Local Gradle
 * builds always use this script.
 *
 * The generated android/ directory is gitignored. This plugin is the source of
 * truth, and `npx expo prebuild --platform android` recreates it.
 */

const GRADLE_FILE = "release-signing.gradle";

const RELEASE_SIGNING_GRADLE = `// Generated by plugins/withAndroidReleaseSigning.js. Do not edit the generated
// android/ tree by hand; run \`npx expo prebuild --platform android\`.
//
// Debug builds keep the debug keystore. Release builds require the upload key:
// an absent credential is a build failure, never a debug-signed artifact.

def uxcKeystoreProperties = new Properties()
def uxcKeystorePropertiesFile = rootProject.file("keystore.properties")
if (uxcKeystorePropertiesFile.exists()) {
    uxcKeystorePropertiesFile.withInputStream { uxcKeystoreProperties.load(it) }
}

def uxcEnv = { String name -> System.getenv(name)?.trim() }
def uxcStoreFile = uxcEnv("UXCOMMUNITY_ANDROID_STORE_FILE") ?: uxcKeystoreProperties.getProperty("storeFile")
def uxcStorePassword = uxcEnv("UXCOMMUNITY_ANDROID_STORE_PASSWORD") ?: uxcKeystoreProperties.getProperty("storePassword")
def uxcKeyAlias = uxcEnv("UXCOMMUNITY_ANDROID_KEY_ALIAS") ?: uxcKeystoreProperties.getProperty("keyAlias")
def uxcKeyPassword = uxcEnv("UXCOMMUNITY_ANDROID_KEY_PASSWORD") ?: uxcKeystoreProperties.getProperty("keyPassword")
def uxcReleaseSigningConfigured = [uxcStoreFile, uxcStorePassword, uxcKeyAlias, uxcKeyPassword].every { value ->
    value != null && !value.isEmpty()
}

android {
    signingConfigs {
        release {
            if (uxcReleaseSigningConfigured) {
                storeFile rootProject.file(uxcStoreFile)
                storePassword uxcStorePassword
                keyAlias uxcKeyAlias
                keyPassword uxcKeyPassword
            }
        }
    }
    buildTypes {
        release {
            // Overrides the template's debug signing. The guard below refuses
            // to run a release task when the signing values are incomplete.
            signingConfig signingConfigs.release
        }
    }
}

gradle.taskGraph.whenReady { graph ->
    def releaseRequested = graph.allTasks.any { task ->
        task.project == project && task.name.contains("Release")
    }
    if (releaseRequested && !uxcReleaseSigningConfigured) {
        throw new GradleException(
            "Release signing credentials are missing. Set " +
            "UXCOMMUNITY_ANDROID_STORE_FILE, UXCOMMUNITY_ANDROID_STORE_PASSWORD, " +
            "UXCOMMUNITY_ANDROID_KEY_ALIAS and UXCOMMUNITY_ANDROID_KEY_PASSWORD, or create " +
            "android/keystore.properties with storeFile, storePassword, keyAlias and keyPassword. " +
            "Refusing to build a release signed with the debug keystore."
        )
    }
}
`;

function withReleaseSigningFile(config) {
  return withDangerousMod(config, [
    "android",
    async (config) => {
      const target = path.join(
        config.modRequest.platformProjectRoot,
        "app",
        GRADLE_FILE,
      );
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, RELEASE_SIGNING_GRADLE);
      return config;
    },
  ]);
}

function withReleaseSigningApply(config) {
  return withAppBuildGradle(config, (config) => {
    const applyLine = `apply from: "${GRADLE_FILE}"`;
    if (!config.modResults.contents.includes(applyLine)) {
      config.modResults.contents =
        `${config.modResults.contents.trimEnd()}\n\n` +
        `// Release signing is fail-closed; see plugins/withAndroidReleaseSigning.js.\n` +
        `${applyLine}\n`;
    }
    return config;
  });
}

function withAndroidReleaseSigning(config) {
  if (process.env.EAS_BUILD === "true") {
    // EAS injects the upload keystore and rewrites the signing configuration
    // after Prebuild. A local fail-closed script would run before that and
    // reject a legitimate EAS build.
    return config;
  }
  return withReleaseSigningApply(withReleaseSigningFile(config));
}

module.exports = withAndroidReleaseSigning;
